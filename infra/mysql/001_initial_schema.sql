CREATE TABLE IF NOT EXISTS import_batch (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  batch_key VARCHAR(160) NOT NULL,
  dataset_type VARCHAR(64) NOT NULL,
